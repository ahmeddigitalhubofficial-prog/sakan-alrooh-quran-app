  static List<QuranLibraryStory> getStoriesByCategory(String category) {
    if (category == 'all') return getAllStories();
    return getAllStories().where((s) => s.category == category).toList();
  }

  static List<QuranLibraryStory> searchStories(String query) {
    if (query.trim().isEmpty) return getAllStories();
    final q = query.trim().toLowerCase();
    return getAllStories().where((s) {
      return s.title.toLowerCase().contains(q) ||
          s.summary.toLowerCase().contains(q) ||
          s.fullStory.toLowerCase().contains(q) ||
          (s.surahName != null && s.surahName!.contains(q)) ||
          s.location.contains(q);
    }).toList();
  }
