  static String get(String key, String localeCode) {
    final langMap = _values[localeCode] ?? _values['ar']!;
    return langMap[key] ?? _values['ar']![key] ?? key;
  }

  static String of(BuildContext context, String key) {
    try {
      final localeManager = Provider.of<LocaleManager>(context, listen: false);
      return get(key, localeManager.currentLocaleCode);
    } catch (_) {
      return get(key, 'ar');
    }
  }
