// ignore_for_file: avoid_print

import 'dart:io';

void main() {
  final pubspecFile = File('pubspec.yaml');
  if (!pubspecFile.existsSync()) {
    print('Error: pubspec.yaml not found.');
    exit(1);
  }

  final content = pubspecFile.readAsStringSync();
  final versionRegExp = RegExp(r'^version:\s*(\d+)\.(\d+)\.(\d+)\+(\d+)', multiLine: true);
  final match = versionRegExp.firstMatch(content);

  if (match == null) {
    print('Error: Could not find version line in pubspec.yaml.');
    exit(1);
  }

  int major = int.parse(match.group(1)!);
  int minor = int.parse(match.group(2)!);
  int patch = int.parse(match.group(3)!);
  int build = int.parse(match.group(4)!);

  build++;

  final newVersion = '$major.$minor.$patch+$build';
  final newVersionLine = 'version: $newVersion';
  final updatedContent = content.replaceFirst(versionRegExp, newVersionLine);
  pubspecFile.writeAsStringSync(updatedContent);

  print('⚡ Auto-bumped build number to: $build (Version: $newVersion)');

  // Update lib/core/constants/app_version.dart
  final versionFile = File('lib/core/constants/app_version.dart');
  if (!versionFile.parent.existsSync()) {
    versionFile.parent.createSync(recursive: true);
  }
  versionFile.writeAsStringSync('''// Generated by scripts/bump_build.dart. Do not modify.
class AppVersion {
  static const String version = '$major.$minor.$patch';
  static const int buildNumber = $build;
}
''');
  print('Updated lib/core/constants/app_version.dart');
}
