// ignore_for_file: avoid_print

import 'dart:io';

void main(List<String> args) {
  print('=== Automated Changelog Manager - Sakan Al-Rooh ===\n');

  // 1. Get the change description
  String? description;
  if (args.isNotEmpty) {
    description = args[0];
  }

  if (description == null || description.trim().isEmpty) {
    stdout.write('✍️ Enter change description (e.g. Added changelog button in settings): ');
    description = stdin.readLineSync();
    if (description == null || description.trim().isEmpty) {
      print('❌ Error: Change description is required.');
      exit(1);
    }
  }
  description = description.trim();

  // 2. Get the category of the change
  String? category;
  if (args.length > 1) {
    category = args[1].toLowerCase();
  }

  if (category == null) {
    print('\n📂 Select change category:');
    print('1. Improvements and new features (Improvements / Features)');
    print('2. Bug fixes (Fixes / Bugfixes)');
    print('3. Minor patches and updates (Patches)');
    stdout.write('Select number (1-3): ');
    final choice = stdin.readLineSync()?.trim();
    if (choice == '1') {
      category = 'improvements';
    } else if (choice == '2') {
      category = 'fixes';
    } else if (choice == '3') {
      category = 'patches';
    } else {
      print('❌ Error: Invalid selection.');
      exit(1);
    }
  } else {
    if (category == '1' || category.startsWith('imp')) category = 'improvements';
    if (category == '2' || category.startsWith('fix')) category = 'fixes';
    if (category == '3' || category.startsWith('pat')) category = 'patches';
  }

  if (category != 'improvements' && category != 'fixes' && category != 'patches') {
    print('❌ Error: Invalid category. Use improvements, fixes, or patches.');
    exit(1);
  }

  // 3. Ask for version bump
  bool shouldBump = false;
  print('\n🔄 Do you want to bump the app version (Version Bump)?');
  print('1. Yes, bump patch version (e.g. 1.0.2 to 1.0.3)');
  print('2. No, append this change to current version in changelog');
  stdout.write('Select number (1-2): ');
  final bumpChoice = stdin.readLineSync()?.trim();
  if (bumpChoice == '1') {
    shouldBump = true;
  } else if (bumpChoice != '2') {
    print('❌ Error: Invalid selection.');
    exit(1);
  }

  // Load pubspec.yaml
  final pubspecFile = File('pubspec.yaml');
  if (!pubspecFile.existsSync()) {
    print('❌ Error: pubspec.yaml not found.');
    exit(1);
  }

  final pubspecContent = pubspecFile.readAsStringSync();
  final versionRegExp = RegExp(r'^version:\s*(\d+)\.(\d+)\.(\d+)\+(\d+)', multiLine: true);
  final match = versionRegExp.firstMatch(pubspecContent);

  if (match == null) {
    print('❌ Error: Could not parse app version from pubspec.yaml');
    exit(1);
  }

  int major = int.parse(match.group(1)!);
  int minor = int.parse(match.group(2)!);
  int patch = int.parse(match.group(3)!);
  int build = int.parse(match.group(4)!);

  String currentVersion = '$major.$minor.$patch';

  if (shouldBump) {
    // Increment version
    patch++;
    build++;
    final newVersion = '$major.$minor.$patch+$build';
    final newVersionLine = 'version: $newVersion';
    final updatedPubspec = pubspecContent.replaceFirst(versionRegExp, newVersionLine);
    pubspecFile.writeAsStringSync(updatedPubspec);
    print('✅ Version bumped in pubspec.yaml to: $newVersion');

    // Update app_version.dart
    final versionFile = File('lib/core/constants/app_version.dart');
    if (!versionFile.parent.existsSync()) {
      versionFile.parent.createSync(recursive: true);
    }
    versionFile.writeAsStringSync('''// Generated by scripts/record_change.dart. Do not modify.
class AppVersion {
  static const String version = '$major.$minor.$patch';
  static const int buildNumber = $build;
}
''');
    print('✅ Updated lib/core/constants/app_version.dart');
    currentVersion = '$major.$minor.$patch';
  }

  // 4. Update CHANGELOG.md
  final changelogFile = File('CHANGELOG.md');
  if (!changelogFile.existsSync()) {
    changelogFile.writeAsStringSync('# Changelog\n\n');
  }

  final changelogContent = changelogFile.readAsStringSync();
  final today = DateTime.now().toIso8601String().substring(0, 10);

  if (shouldBump || !changelogContent.contains('## [$currentVersion]')) {
    // Create new version block at the top of changelog
    stdout.write('\n🏷️ Enter title for this new release (e.g. General Bug Fixes): ');
    var title = stdin.readLineSync()?.trim();
    if (title == null || title.isEmpty) {
      title = shouldBump ? 'General Updates & Fixes' : 'General Update';
    }

    stdout.write('📝 Enter short description for release (or press Enter for default): ');
    var desc = stdin.readLineSync()?.trim();
    if (desc == null || desc.isEmpty) {
      desc = 'Performance improvements, bug fixes, and general enhancements across various app features.';
    }

    String newBlock = '## [$currentVersion] - $today\n';
    newBlock += '### Title: $title\n';
    newBlock += '### Description: $desc\n\n';

    if (category == 'improvements') {
      newBlock += '### Improvements\n- $description\n\n';
      newBlock += '### Fixes\n- \n\n';
      newBlock += '### Patches\n- \n\n';
    } else if (category == 'fixes') {
      newBlock += '### Improvements\n- \n\n';
      newBlock += '### Fixes\n- $description\n\n';
      newBlock += '### Patches\n- \n\n';
    } else {
      newBlock += '### Improvements\n- \n\n';
      newBlock += '### Fixes\n- \n\n';
      newBlock += '### Patches\n- $description\n\n';
    }

    // Insert new version block right after '# Changelog'
    if (changelogContent.startsWith('# Changelog')) {
      final idx = changelogContent.indexOf('\n\n');
      if (idx != -1) {
        final prefix = changelogContent.substring(0, idx + 2);
        final suffix = changelogContent.substring(idx + 2);
        changelogFile.writeAsStringSync('$prefix$newBlock$suffix');
      } else {
        changelogFile.writeAsStringSync('$changelogContent\n\n$newBlock');
      }
    } else {
      changelogFile.writeAsStringSync('# Changelog\n\n$newBlock$changelogContent');
    }
    print('🎉 Created new release section $currentVersion and added change successfully!');
  } else {
    // Append change to existing top version block
    final lines = changelogContent.split('\n');
    int insertIndex = -1;
    bool foundVersion = false;
    String targetHeader = '';

    if (category == 'improvements') targetHeader = '### Improvements';
    if (category == 'fixes') targetHeader = '### Fixes';
    if (category == 'patches') targetHeader = '### Patches';

    for (int i = 0; i < lines.length; i++) {
      final line = lines[i].trim();
      if (line.startsWith('## [$currentVersion]')) {
        foundVersion = true;
        continue;
      }
      if (foundVersion) {
        // If we hit another version, we missed the target in the current version
        if (line.startsWith('## [')) {
          break;
        }
        if (line == targetHeader) {
          // Find the end of this list
          insertIndex = i + 1;
          // Look for existing bullet points or empty bullet point
          while (insertIndex < lines.length) {
            final nextLine = lines[insertIndex].trim();
            if (nextLine.startsWith('-') || nextLine.startsWith('*')) {
              // If it's a placeholder empty bullet point, we can replace it
              if (nextLine == '-' || nextLine == '- -') {
                lines.removeAt(insertIndex);
                break;
              }
              insertIndex++;
            } else {
              break;
            }
          }
          break;
        }
      }
    }

    if (insertIndex != -1) {
      lines.insert(insertIndex, '- $description');
      changelogFile.writeAsStringSync(lines.join('\n'));
      print('🎉 Added new change successfully under $currentVersion in section $targetHeader!');
    } else {
      print('❌ Error: Could not find section under version $currentVersion in CHANGELOG.md');
      exit(1);
    }
  }
}
