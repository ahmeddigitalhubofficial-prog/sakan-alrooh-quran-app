// ignore_for_file: avoid_print

import 'dart:io';

void main(List<String> arguments) {
  if (arguments.isEmpty) {
    print('Usage: dart run scripts/bump_version.dart <major|minor|patch>');
    exit(1);
  }

  final type = arguments[0].toLowerCase();
  if (type != 'major' && type != 'minor' && type != 'patch') {
    print('Invalid bump type: $type. Use major, minor, or patch.');
    exit(1);
  }

  final pubspecFile = File('pubspec.yaml');
  if (!pubspecFile.existsSync()) {
    print('Error: pubspec.yaml not found.');
    exit(1);
  }

  final content = pubspecFile.readAsStringSync();
  final versionRegExp = RegExp(r'^version:\s*(\d+)\.(\d+)\.(\d+)\+(\d+)', multiLine: true);
  final match = versionRegExp.firstMatch(content);

  if (match == null) {
    print('Error: Could not find version line in pubspec.yaml.');
    exit(1);
  }

  int major = int.parse(match.group(1)!);
  int minor = int.parse(match.group(2)!);
  int patch = int.parse(match.group(3)!);
  int build = int.parse(match.group(4)!);

  if (type == 'major') {
    major++;
    minor = 0;
    patch = 0;
  } else if (type == 'minor') {
    minor++;
    patch = 0;
  } else if (type == 'patch') {
    patch++;
  }

  build++;

  final newVersion = '$major.$minor.$patch+$build';
  final newVersionLine = 'version: $newVersion';
  final updatedContent = content.replaceFirst(versionRegExp, newVersionLine);
  pubspecFile.writeAsStringSync(updatedContent);

  print('Successfully bumped version to: $newVersion');

  // Update lib/core/constants/app_version.dart
  final versionFile = File('lib/core/constants/app_version.dart');
  if (!versionFile.parent.existsSync()) {
    versionFile.parent.createSync(recursive: true);
  }
  versionFile.writeAsStringSync('''// Generated by scripts/bump_version.dart. Do not modify.
class AppVersion {
  static const String version = '$major.$minor.$patch';
  static const int buildNumber = $build;
}
''');
  print('Updated lib/core/constants/app_version.dart');

  // Update CHANGELOG.md
  final changelogFile = File('CHANGELOG.md');
  final today = DateTime.now().toIso8601String().substring(0, 10);

  String changelogHeader = '## [$major.$minor.$patch] - $today\n';
  changelogHeader += '### Title: Enter Title Here\n';
  changelogHeader += '### Description: Enter Description Here\n\n';
  changelogHeader += '### Improvements\n- \n\n';
  changelogHeader += '### Fixes\n- \n\n';
  changelogHeader += '### Patches\n- \n\n';

  if (changelogFile.existsSync()) {
    final existingChangelog = changelogFile.readAsStringSync();
    if (existingChangelog.startsWith('# Changelog')) {
      final splitIndex = existingChangelog.indexOf('\n\n');
      if (splitIndex != -1) {
        final titlePart = existingChangelog.substring(0, splitIndex + 2);
        final restPart = existingChangelog.substring(splitIndex + 2);
        changelogFile.writeAsStringSync('$titlePart$changelogHeader$restPart');
      } else {
        changelogFile.writeAsStringSync('$existingChangelog\n\n$changelogHeader');
      }
    } else {
      changelogFile.writeAsStringSync('$changelogHeader$existingChangelog');
    }
  } else {
    changelogFile.writeAsStringSync('# Changelog\n\n$changelogHeader');
  }

  print('Updated CHANGELOG.md with a new release section.');
}
